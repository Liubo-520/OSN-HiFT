"""Generate Supplementary Tables (Markdown) directly from result files."""
import json

import numpy as np
import pandas as pd

from osn_core import DATA, HERE, RESULTS

OUT = HERE / "manuscript"
OUT.mkdir(exist_ok=True)
K = json.load(open(RESULTS / "key_numbers.json", encoding="utf-8"))


def md(df, floatfmt=3):
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{floatfmt}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


parts = ["# Supplementary Tables\n",
         "All tables are generated by `21_si_tables.py` from the analysis outputs; values are not edited by hand.\n"]

a = K["curation"]
rows = []
for tag in ["pure_solvent_permeance", "solution_permeance"]:
    for step in ["numeric", "accepted", "single_solvent", "organic", "descriptor_known", "positive"]:
        s = a[f"{tag}:{step}"]
        rows.append(dict(target=tag.replace("_", " "), step=step.replace("_", " "), rows=s["rows"], papers=s["papers"],
                         removed=s["removed_from_previous"]))
parts += ["## Table S1. Record-level curation audit\n", md(pd.DataFrame(rows)),
          f"\nRejection (solute slots 1–12 unpacked): {a['rejection:long_values']} values; {a['rejection:negative']} "
          f"negative and {a['rejection:above_100']} >100% values excluded; {a['rejection:modelled_rows']} modelled values "
          f"from {a['rejection:papers']} papers and {a['rejection:solutes']} solutes.\n"]

sd = pd.read_csv(DATA / "solvent_descriptors.csv", index_col=0)
sd = sd[["short", "MW", "rho", "eta", "Vm", "dD", "dP", "dH", "eps", "gamma"]].reset_index()
sd.columns = ["Solvent", "Abbr.", "MW (g/mol)", "ρ (g/cm³)", "η (mPa s)", "Vm (cm³/mol)", "δD", "δP", "δH", "ε", "γ (mN/m)"]
parts += ["## Table S2. Solvent descriptors (25 °C)\n",
          "HSP: Hansen Solubility Parameters handbook (2nd ed., 2007); other properties: CRC Handbook of Chemistry and "
          "Physics. Values must be re-verified against the printed sources before submission.\n", md(sd, 3), ""]

met = pd.read_csv(RESULTS / "benchmark_metrics.csv")
met = met[["scenario", "model", "n_rows", "n_papers", "R2", "R2_lo", "R2_hi", "MAE", "MAE_lo", "MAE_hi", "rho"]]
parts += ["## Table S3. Zero-shot benchmark (log10 pure-solvent permeance)\n",
          "Point estimates are seed-averaged (3 seeds where applicable); 95% CIs from 1,000 paper-cluster bootstrap "
          "resamples.\n", md(met), ""]
rj = pd.read_csv(RESULTS / "rejection_benchmark.csv")
rj["MAE (pp)"] = 100 * rj["MAE"]
parts += ["## Table S4. Zero-shot benchmark (solute rejection)\n",
          md(rj[["scenario", "model", "n_rows", "n_papers", "R2", "R2_lo", "R2_hi", "MAE (pp)"]]), ""]
tc = pd.read_csv(RESULTS / "temporal_control.csv")
parts += ["## Table S5. Temporal drift versus training-set size (LightGBM, 10 random halvings of ≥2021 papers)\n",
          md(tc.groupby("training")[["R2", "MAE", "n_train_rows", "n_train_papers"]].agg(["mean", "std"])
             .round(3).reset_index().set_axis(["training", "R2 mean", "R2 SD", "MAE mean", "MAE SD", "rows mean",
                                               "rows SD", "papers mean", "papers SD"], axis=1)), ""]

vc = pd.read_csv(RESULTS / "variance_components.csv")
parts += ["## Table S6. Variance components (REML mixed model; 95% CI from 100 paper bootstraps)\n",
          md(vc[["dataset", "basis", "n_cells", "n_papers", "n_membranes", "share_paper", "share_paper_lo",
                 "share_paper_hi", "share_membrane", "share_residual"]]), ""]
ns = pd.DataFrame(K["noise"]).T.reset_index().rename(columns={"index": "dataset"})
parts += ["## Table S7. Reproducibility ceilings\n",
          md(ns[["dataset", "interlab_cells", "interlab_papers", "interlab_sd", "interlab_sd_lo", "interlab_sd_hi",
                 "matched_cells", "matched_interlab_sd", "within_paper_replicate_groups", "within_paper_sd",
                 "mae_floor_interlab", "r2_ceiling_unseen_paper"]]), ""]
ic = pd.read_csv(RESULTS / "interlab_cells.csv")
ic = ic[ic.dataset == "Pure-solvent permeance"][["commercialName", "testConditions.solvent1", "report.reference", "y"]]
ic.columns = ["Commercial membrane", "Solvent", "Source (DOI)", "log10 P (paper median)"]
parts += ["## Table S8. Inter-laboratory records used for the reproducibility ceiling (pure-solvent permeance)\n",
          md(ic.sort_values(["Commercial membrane", "Solvent"]), 2), ""]

for tag, lab in [("sp", "pure-solvent permeance, membranes with ≥4 solvents"),
                 ("pm", "solution permeance, membranes with ≥3 solvents")]:
    s = pd.read_csv(RESULTS / f"fewshot_summary_{tag}.csv")
    s = s.pivot_table(index="method", columns="k", values="mae").round(3)
    s.columns = [f"k = {c}" for c in s.columns]
    parts += [f"## Table S{9 if tag == 'sp' else 10}. Few-shot MAE (log10; {lab}; 3 seeds × 5 paper folds)\n",
              md(s.reset_index()), ""]
pp = pd.read_csv(RESULTS / "fewshot_paired_sp.csv")
parts += ["## Table S11. Paired differences versus HiFT (pure-solvent permeance; >0: HiFT better; 95% paper-bootstrap CI)\n",
          md(pp), ""]
for tag, n in [("sp", 12), ("pm", 13)]:
    c = pd.read_csv(RESULTS / f"hift_coverage_{tag}.csv")
    c["fold (±)"] = 10 ** c["half_width_log"]
    parts += [f"## Table S{n}. HiFT interval calibration ({'pure-solvent' if tag == 'sp' else 'solution'} permeance)\n",
              md(c[["k", "level", "coverage", "lo", "hi", "half_width_log", "fold (±)"]]), ""]
cf = pd.read_csv(RESULTS / "conformal_coverage.csv").groupby(["scenario", "calibration", "level"])[
    ["coverage", "width", "paper_coverage_median"]].mean().reset_index()
parts += ["## Table S14. Split-conformal coverage for zero-shot LightGBM (mean over folds and seeds)\n", md(cf), ""]
fp = pd.read_csv(RESULTS / "fingerprints.csv")
g = fp.groupby("material").agg(n=("entity", "size"), visc=("b_log_eta", "mean"), dP=("b_dP", "mean"),
                               dH=("b_dH", "mean"), logVm=("b_log_Vm", "mean")).reset_index()
g["dP"] *= 10
g["dH"] *= 10
g.columns = ["Material class", "n", "∂logP/∂logη", "∂logP/∂(10 δP)", "∂logP/∂(10 δH)", "∂logP/∂logVm"]
parts += ["## Table S15. Class-mean solvent-response fingerprints (posterior means; membranes with ≥3 solvents)\n",
          md(g), ""]
se = pd.read_csv(RESULTS / "solvent_effects.csv")
parts += ["## Table S16. Literature-wide versus within-membrane solvent effects (centred log10 units)\n",
          md(se[["short", "between", "within", "within_lo", "within_hi", "n_cells_all", "n_multi_membranes", "log_eta"]]), ""]
des = pd.read_csv(RESULTS / "anchor_design.csv")
parts += ["## Table S17. Bayesian anchor design (expected reduction of mean predictive variance over the other candidate solvents)\n",
          md(des.sort_values(["k", "reduction"], ascending=[True, False])[["anchor1", "anchor2", "k", "reduction"]]), ""]
emp = pd.read_csv(RESULTS / "anchor_empirical.csv")
parts += ["## Table S18. Empirical single-anchor informativeness (within-membrane centred MAE, HiFT k = 1)\n",
          md(emp[["anchor", "n_membranes", "centered_mae", "lo", "hi", "reduction"]]), ""]
hp = pd.read_csv(RESULTS / "hift_params_pure_solvent_permeance.csv")
hp["sigma"] = np.sqrt(hp["sigma2"])
hp["tau"] = np.sqrt(hp["tau2"])
hp["tau_all"] = np.sqrt(hp["tau2_all"])
parts += ["## Table S19. Fold-wise HiFT variance components (pure-solvent permeance)\n",
          md(hp[["seed", "fold", "sigma", "tau", "tau_all", "n_train_multi", "n_aux_multi"]]), ""]

(OUT / "Supplementary_Tables.md").write_text("\n".join(parts), encoding="utf-8")
print("written", OUT / "Supplementary_Tables.md", sum(len(p) for p in parts), "chars")
